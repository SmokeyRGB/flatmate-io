-- itself be enforced" / "Every writer of the same state, pairwise": one membership per resident
-- profile, and one membership per account, were both assumptions held only by the three writers
-- (registerHousehold, claimResidentProfile, joinHousehold in auth.ts) — nothing in the database
-- stopped a second row. The reset path picks `[membershipRow]` by resident_profile_id
-- (issuePasswordResetLink/redeemPasswordReset), and signIn picks it by account_id
-- (`SELECT ... FOR UPDATE` in auth.ts), so a second row for either would make either pick
-- ambiguous — a real bug, not a defensive one, since drizzle-kit generates `db.select()` without
-- an implicit LIMIT.
--
