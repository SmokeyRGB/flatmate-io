-- Step 5: claim_join_code, now two-argument — the caller STATES which purpose it redeems
-- (design.md Decision 4), so joinHousehold can never spend a reset link and redeemPasswordReset
-- can never spend a joining link, and neither needs a rollback to find out. Both prior overloads
-- (drizzle/0013's one-argument form, and any partial prior run of this file's own two-argument
-- form) are dropped first, so exactly one `claim_join_code` exists afterwards.
DROP FUNCTION IF EXISTS claim_join_code(text);
--> statement-breakpoint
DROP FUNCTION IF EXISTS claim_join_code(text, join_code_purpose);
--> statement-breakpoint
CREATE FUNCTION claim_join_code(p_code text, p_purpose join_code_purpose) RETURNS TABLE (
  household_id uuid,
  issuance_id uuid,
  household_name text,
  bound_resident_profile_id uuid,
  bound_resident_display_name text,
  purpose join_code_purpose
)
LANGUAGE sql SECURITY DEFINER SET search_path = public VOLATILE AS $$
  WITH claimed AS (
    UPDATE "join_code_issuance"
       SET uses = uses + 1
     WHERE code = p_code
       AND purpose = p_purpose
       AND deleted_at IS NULL
       AND expires_at > now()
       AND uses < max_uses
       -- Same predicate as resolve_join_code's WHERE, evaluated in the SAME statement as the
       -- increment so a link that is no longer valid cannot be spent. This does NOT by itself
       -- settle two links racing for one profile (join) or one account (reset): they update
       -- DIFFERENT issuance rows, so nothing serializes them here. The conditional UPDATE on
       -- resident_profile in joinHousehold's bound branch, and the membership/account
       -- `FOR UPDATE` re-check in redeemPasswordReset, are what decide those cases — each takes a
       -- row lock, so the loser matches zero rows and its whole transaction, this increment
       -- included, rolls back.
       AND (
         (purpose = 'join' AND (
           resident_profile_id IS NULL
           OR EXISTS (
             SELECT 1 FROM "resident_profile" rp
             WHERE rp.id = "join_code_issuance".resident_profile_id
               AND rp.household_id = "join_code_issuance".household_id
               AND rp.status = 'prepared'
           )
         ))
         OR
         (purpose = 'password_reset' AND EXISTS (
           SELECT 1 FROM "resident_profile" rp
           JOIN "membership" m ON m.resident_profile_id = rp.id AND m.household_id = "join_code_issuance".household_id
           JOIN "account" a ON a.id = m.account_id AND a.household_id = "join_code_issuance".household_id
           WHERE rp.id = "join_code_issuance".resident_profile_id
             AND rp.household_id = "join_code_issuance".household_id
             AND rp.status = 'active' AND m.revoked_at IS NULL AND a.email IS NULL
         ))
       )
    RETURNING household_id, id AS issuance_id, resident_profile_id, purpose
  )
  SELECT h.id, claimed.issuance_id, h.name, rp.id, rp.display_name, claimed.purpose
  FROM claimed
  JOIN "household" h ON h.id = claimed.household_id
  -- Same household predicate, same reasoning as resolve_join_code above.
  LEFT JOIN "resident_profile" rp
    ON rp.id = claimed.resident_profile_id AND rp.household_id = claimed.household_id
  WHERE h.deleted_at IS NULL
$$;
--> statement-breakpoint
REVOKE ALL ON FUNCTION claim_join_code(text, join_code_purpose) FROM PUBLIC;
--> statement-breakpoint
GRANT EXECUTE ON FUNCTION claim_join_code(text, join_code_purpose) TO app_runtime;
