-- Step 4: resolve_join_code, replaced to also return `purpose` and to judge a reset link's
-- validity, not only a joining one's. STABLE, non-consuming — unchanged in every other respect
-- from drizzle/0015's version for the joining branch.
DROP FUNCTION IF EXISTS resolve_join_code(text);
--> statement-breakpoint
CREATE FUNCTION resolve_join_code(p_code text) RETURNS TABLE (
  household_id uuid,
  issuance_id uuid,
  household_name text,
  bound_resident_profile_id uuid,
  bound_resident_display_name text,
  purpose join_code_purpose
)
LANGUAGE sql SECURITY DEFINER SET search_path = public STABLE AS $$
  SELECT h.id, jci.id, h.name, rp.id, rp.display_name, jci.purpose
  FROM "join_code_issuance" jci
  JOIN "household" h ON h.id = jci.household_id
  -- The household predicate is NOT redundant with issueJoinCodeTx's/issuePasswordResetLink's own
  -- checks. This function is SECURITY DEFINER, so it runs past RLS, and it answers an
  -- UNAUTHENTICATED caller; there are no foreign keys in this schema, so nothing but application
  -- code keeps this column honest. Were a binding ever wrong — a bug, a hand-edited row, a bad
  -- backfill — the two output columns would disclose another household's profile id and display
  -- name to a stranger holding a code. With the predicate they come back null instead, which is
  -- the same outcome as a neutral link (an invalid reset link, for the reset branch below).
  LEFT JOIN "resident_profile" rp
    ON rp.id = jci.resident_profile_id AND rp.household_id = jci.household_id
  WHERE jci.code = p_code
    AND jci.deleted_at IS NULL
    AND jci.expires_at > now()
    AND jci.uses < jci.max_uses
    AND h.deleted_at IS NULL
    AND (
      -- A JOINING link, bound or neutral: unchanged from drizzle/0015. A BOUND joining link is
      -- valid only while the profile it names is still claimable, in its own household (third
      -- review of PR #17). `rp.id IS NOT NULL` additionally makes a CORRUPT binding (one pointing
      -- outside this household, which the join above already refuses to match) kill the link
      -- outright rather than letting it behave as a neutral one.
      (jci.purpose = 'join' AND (jci.resident_profile_id IS NULL OR (rp.id IS NOT NULL AND rp.status = 'prepared')))
      OR
      -- A RESET link (identity/password-reset): valid only while its named profile is ACTIVE, its
      -- membership is live (not revoked), and — the gap it closes — the account still has no
      -- email. Every join carries its own household_id predicate (CLAUDE.md "A SECURITY DEFINER
      -- function"): a corrupt membership or account row whose household_id differs must not make
      -- a reset link valid, exactly as a corrupt resident_profile binding must not above.
      -- `a.email IS NULL` is a predicate here, never an output column — the function discloses
      -- only the display name the person is greeted by (spec: "no email, account id or status is
      -- returned").
      (jci.purpose = 'password_reset' AND rp.id IS NOT NULL AND rp.status = 'active'
         AND EXISTS (
           SELECT 1 FROM "membership" m
           JOIN "account" a ON a.id = m.account_id AND a.household_id = jci.household_id
           WHERE m.resident_profile_id = rp.id AND m.household_id = jci.household_id
             AND m.revoked_at IS NULL AND a.email IS NULL
         ))
    )
$$;
--> statement-breakpoint
REVOKE ALL ON FUNCTION resolve_join_code(text) FROM PUBLIC;
--> statement-breakpoint
GRANT EXECUTE ON FUNCTION resolve_join_code(text) TO app_runtime;
