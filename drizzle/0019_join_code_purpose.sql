-- resident-settings design.md Decision 4 (Migration Plan). A join link gains a `purpose`
-- (`join` / `password_reset`); a reset link is a bound link naming an ACTIVE profile whose
-- account has no email (identity/password-reset). Steps 1-3 are a plain column/constraint add,
-- generated by drizzle-kit from schema.ts and hand-edited here to be re-runnable (DO ... EXCEPTION
-- WHEN duplicate_object for the CREATE TYPE, IF NOT EXISTS for the column, DROP CONSTRAINT IF
-- EXISTS before ADD CONSTRAINT). Steps 4-6 replace both SECURITY DEFINER functions and are a
-- HUMAN HAND-OFF (tasks.md 2.4): the harness refuses SECURITY DEFINER statements, so an agent can
-- apply only steps 1-3, and a human runs this WHOLE file afterwards in the Supabase SQL editor —
-- which is why every statement here, not only 1-3, is written to survive a partial prior run.
--
-- *** WHY DROP-THEN-CREATE, NOT `CREATE OR REPLACE` (drizzle/0015's lesson) ***
-- resolve_join_code gains an output column (`purpose`); claim_join_code gains an argument
-- (`p_purpose`). Both change the shape Postgres tracks as part of a function's return/argument
-- type, and `CREATE OR REPLACE FUNCTION` refuses that outright ("cannot change return type of
-- existing function / HINT: Use DROP FUNCTION first" — or, for an argument list, simply resolves
-- to a distinct overload instead of replacing anything, which is exactly the hazard Step 5 exists
-- to close). Both `claim_join_code(text)` (0013) and `claim_join_code(text, join_code_purpose)`
-- (any partial prior run of this file) are dropped before the single two-argument function is
-- created, so the OLD one-argument overload cannot survive beside the new one, still callable and
-- still ignoring purpose.
--
-- Ordering against the live constraints: the column arrives with its default ('join') BEFORE the
-- CHECK, so every existing row already satisfies it. The functions come last, so neither is ever
-- created in a shape that references a column that doesn't exist yet.

-- Step 1: the enum type. `CREATE TYPE` has no `IF NOT EXISTS` in this Postgres version, so
-- re-runnability comes from catching the "already exists" error instead (duplicate_object,
-- SQLSTATE 42710) — the same idiom this project already reaches for whenever a plain DDL clause
-- lacks its own guard.
DO $$ BEGIN
  CREATE TYPE "public"."join_code_purpose" AS ENUM('join', 'password_reset');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;
